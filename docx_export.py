"""Builds a downloadable Word file from a GroundedSummaryResult."""
import io

from docx import Document
from docx.shared import Pt


def build_summary_docx(source_filename: str, language_name: str, result) -> bytes:
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)

    doc.add_heading("Summary", level=0)
    meta = doc.add_paragraph()
    meta.add_run("Source document: ").bold = True
    meta.add_run(source_filename)
    meta.add_run("\nLanguage: ").bold = True
    meta.add_run(language_name)
    meta.add_run("\nGenerated by Kàwé.ai").italic = True

    doc.add_heading("Summary text", level=1)
    for section in result.sections:
        doc.add_paragraph(section.summary_text)

    doc.add_heading("Sources", level=1)
    doc.add_paragraph(
        "Each summary section above is traceable to the passage below."
    ).italic = True
    for i, section in enumerate(result.sections, start=1):
        doc.add_heading(f"Section {i} - {section.location_label}", level=2)
        p = doc.add_paragraph()
        p.add_run("Summary: ").bold = True
        p.add_run(section.summary_text)
        q = doc.add_paragraph()
        q.add_run("Original excerpt: ").bold = True
        q.add_run(section.source_excerpt)

    if getattr(result, "skipped_chunks", 0):
        doc.add_paragraph(
            f"Note: {result.skipped_chunks} section(s) could not be summarized "
            "and were skipped."
        )

    doc.add_paragraph(
        "AI-generated summaries can contain errors. Check important details "
        "against the original document."
    )

    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()

