"""Word (.docx) downloads for summaries and translations."""

from __future__ import annotations

import io
from typing import List

from docx import Document
from docx.shared import Pt

DISCLAIMER = "AI-generated summaries can contain errors. Check important details against the original document."


def _new_document(title: str, source_filename: str, language_label: str, language_name: str):
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    doc.add_heading(title, level=0)
    meta = doc.add_paragraph()
    meta.add_run("Source document: ").bold = True
    meta.add_run(source_filename)
    meta.add_run(f"\n{language_label}: ").bold = True
    meta.add_run(language_name)
    meta.add_run("\nGenerated by Kàwé.ai").italic = True
    return doc


def _labelled(doc, label: str, text: str) -> None:
    paragraph = doc.add_paragraph()
    paragraph.add_run(f"{label}: ").bold = True
    paragraph.add_run(text)


def _to_bytes(doc) -> bytes:
    buffer = io.BytesIO()
    doc.save(buffer)
    return buffer.getvalue()


def build_summary_docx(source_filename: str, language_name: str, result) -> bytes:
    doc = _new_document("Summary", source_filename, "Language", language_name)
    doc.add_heading("Summary text", level=1)
    for section in result.sections:
        doc.add_paragraph(section.summary_text)

    doc.add_heading("Sources", level=1)
    doc.add_paragraph("Each summary section above is traceable to the passage below.").italic = True
    for i, section in enumerate(result.sections, start=1):
        doc.add_heading(f"Section {i} - {section.location_label}", level=2)
        _labelled(doc, "Summary", section.summary_text)
        _labelled(doc, "Original excerpt", section.source_excerpt)

    if getattr(result, "skipped_chunks", 0):
        doc.add_paragraph(f"Note: {result.skipped_chunks} section(s) could not be summarized and were skipped.")
    doc.add_paragraph(DISCLAIMER)
    return _to_bytes(doc)


def build_translation_docx(source_filename: str, language_name: str, result, translated_sections: List[str]) -> bytes:
    doc = _new_document(f"Summary ({language_name})", source_filename, "Translated into", language_name)
    doc.add_heading("Summary text", level=1)
    for text in translated_sections:
        doc.add_paragraph(text)

    doc.add_heading("Sources", level=1)
    sections = [s for s in result.sections if s.summary_text.strip()]
    for i, (section, translated) in enumerate(zip(sections, translated_sections), start=1):
        doc.add_heading(f"Section {i} - {section.location_label}", level=2)
        _labelled(doc, language_name, translated)
        _labelled(doc, "Original summary", section.summary_text)
        _labelled(doc, "Original excerpt", section.source_excerpt)

    doc.add_paragraph(
        "This is a machine translation of an AI-generated summary and can contain errors. "
        "Check important details against the original document."
    )
    return _to_bytes(doc)
